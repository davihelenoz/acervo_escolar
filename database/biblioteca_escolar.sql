-- ----------------------------------------------------------------------------
-- 1. CRIAÇÃO DAS TABELAS
-- ----------------------------------------------------------------------------

CREATE TABLE IF NOT EXISTS Usuario (
    id_usuario INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, -- MySQL: INT AUTO_INCREMENT PRIMARY KEY
    nome       VARCHAR(120) NOT NULL,
    email      VARCHAR(150) NOT NULL UNIQUE,
    senha      VARCHAR(255) NOT NULL
);

CREATE TABLE IF NOT EXISTS Livro (
    id_livro   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, -- MySQL: INT AUTO_INCREMENT PRIMARY KEY
    titulo     VARCHAR(180) NOT NULL,
    autor      VARCHAR(140) NOT NULL,
    categoria  VARCHAR(80)  NOT NULL,
    quantidade INTEGER      NOT NULL DEFAULT 0 CHECK (quantidade >= 0)
);

CREATE TABLE IF NOT EXISTS Emprestimo (
    id_emprestimo           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, -- MySQL: INT AUTO_INCREMENT PRIMARY KEY
    data_emprestimo         DATE NOT NULL,
    data_prevista_devolucao DATE NOT NULL,
    data_devolucao          DATE NULL,
    id_usuario              INTEGER NOT NULL,
    id_livro                INTEGER NOT NULL,
    CONSTRAINT fk_emprestimo_usuario FOREIGN KEY (id_usuario) REFERENCES Usuario(id_usuario),
    CONSTRAINT fk_emprestimo_livro   FOREIGN KEY (id_livro)   REFERENCES Livro(id_livro)
);

